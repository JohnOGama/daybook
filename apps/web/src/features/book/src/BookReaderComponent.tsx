'use client';

import { generateHTML } from '@tiptap/react';
import { ArrowLeft, Printer } from 'lucide-react';
import Link from 'next/link';
import { useMemo } from 'react';
import { createPortal } from 'react-dom';
import { EDITOR_EXTENSIONS, type NotebookPage } from '@/features/notebook';
import { Button } from '@/shared/components/ui/button';
import { authClient } from '@/shared/services/auth-client';
import { chapterTitle, formatWords, wordCount } from './book-stats';

type BookBodyProps = {
  title: string;
  author?: string;
  chapters: NotebookPage[];
  chapterHtml: string[];
  withAnchors?: boolean;
};

function BookBody({ title, author, chapters, chapterHtml, withAnchors }: BookBodyProps) {
  const anchor = (index: number) => (withAnchors ? `chapter-${index + 1}` : undefined);

  return (
    <article className="book-prose mx-auto max-w-[38rem] px-5 pb-32">
      <header className="book-title-page py-20 text-center md:py-28">
        <h1 className="text-4xl leading-tight font-semibold tracking-tight text-balance md:text-5xl">{title}</h1>
        {author && <p className="mt-4 text-lg text-muted-foreground">by {author}</p>}
      </header>

      <nav aria-label="Contents" className="book-contents border-t py-10">
        <h2 className="mb-4 text-sm font-medium tracking-widest text-muted-foreground uppercase">Contents</h2>
        <ol className="flex flex-col gap-2">
          {chapters.map((chapter, index) => (
            <li key={chapter.id} className="flex gap-4">
              <span className="w-6 shrink-0 text-right text-muted-foreground tabular-nums">{index + 1}</span>
              {withAnchors ? (
                <a href={`#${anchor(index)}`} className="hover:underline hover:underline-offset-4">
                  {chapterTitle(chapter)}
                </a>
              ) : (
                <span>{chapterTitle(chapter)}</span>
              )}
            </li>
          ))}
        </ol>
      </nav>

      {chapters.map((chapter, index) => (
        <section key={chapter.id} id={anchor(index)} className="book-chapter scroll-mt-14 border-t pt-16 pb-6">
          <p className="text-sm font-medium tracking-widest text-muted-foreground uppercase">Chapter {index + 1}</p>
          <h2 className="mt-2 mb-10 text-3xl leading-tight font-semibold tracking-tight text-balance">
            {chapterTitle(chapter)}
          </h2>
          {/* Generated by Tiptap from the writer's own saved document; text is escaped by its serializer. */}
          <div className="page-content" dangerouslySetInnerHTML={{ __html: chapterHtml[index] }} />
        </section>
      ))}
    </article>
  );
}

type BookReaderProps = { title: string; chapters: NotebookPage[]; backHref: string };

export function BookReaderComponent({ title, chapters, backHref }: BookReaderProps) {
  const author = authClient.useSession().data?.user.name;
  const chapterHtml = useMemo(
    () => chapters.map((chapter) => (chapter.content ? generateHTML(chapter.content, EDITOR_EXTENSIONS) : '')),
    [chapters],
  );
  const words = chapters.reduce((total, chapter) => total + wordCount(chapter.content), 0);
  const book = { title, author, chapters, chapterHtml };

  return (
    <div>
      <div className="sticky top-0 z-10 flex items-center justify-between gap-2 border-b bg-background/85 px-3 py-2 backdrop-blur md:px-5">
        <Button asChild variant="ghost" size="sm">
          <Link href={backHref}>
            <ArrowLeft aria-hidden />
            Back to writing
          </Link>
        </Button>
        <span className="hidden text-[13px] text-muted-foreground sm:inline">{formatWords(words)}</span>
        <Button variant="outline" size="sm" onClick={() => window.print()}>
          <Printer aria-hidden />
          Print or save as PDF
        </Button>
      </div>
      <BookBody {...book} withAnchors />
      {typeof document !== 'undefined' &&
        createPortal(
          <div className="book-print" aria-hidden>
            <BookBody {...book} />
          </div>,
          document.body,
        )}
    </div>
  );
}
